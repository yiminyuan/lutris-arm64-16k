#!/bin/bash
# Installs this branch of Lutris with upstream's meson build into upstream's
# default prefix, /usr/local (bin/lutris, lib/python3.X/site-packages/lutris,
# share/lutris, ...). User data stays in ~/.local/share/lutris as usual.
#
# A per-user prefix such as ~/.local does not work: meson would install
# share/lutris into ~/.local/share/lutris, Lutris's own data directory, and
# bin/lutris drops every /home path from sys.path. Fedora's site.py adds
# /usr/local/lib/python3.X/site-packages to sys.path when it exists, so
# reinstall after a Python upgrade.
#
# What gets installed is the committed HEAD, exported with git archive, so
# the install never contains uncommitted changes or stray __pycache__
# directories. Building runs as the user, and so does a staged install
# (DESTDIR) that lists exactly what will be installed, including the bytecode
# meson compiles but leaves out of its own install log. Only installing and
# removing files in /usr/local uses sudo. The list is kept in $XDG_STATE_HOME
# so that an upgrade removes files the new version no longer installs and
# --uninstall removes exactly the installed files and the directories the
# install created.
#
# usage: ./install.sh              build HEAD and install (or upgrade) it
#        ./install.sh --uninstall  remove the installed files
set -euo pipefail

REPO=$(git -C "$(dirname "$(readlink -f "$0")")" rev-parse --show-toplevel)
PREFIX=/usr/local

absolute_or () {  # value default
  case $1 in /*) echo "$1" ;; *) echo "$2" ;; esac
}
STATE_DIR=$(absolute_or "${XDG_STATE_HOME:-}" "$HOME/.local/state")/lutris-arm64-16k
# One entry per line: "file <path>" for an installed file or symlink, and
# "dir <path>" for a directory the install created.
LOG=$STATE_DIR/installed.txt

die () { echo "install.sh: $*" >&2; exit 1; }

# Files and directories created as root must be readable by everyone, and
# meson copies the modes of the files it installs.
umask 022

# Prints its arguments one per line, and nothing at all for no arguments.
lines () {
  if [ $# -gt 0 ]; then
    printf '%s\n' "$@"
  fi
}

# Sorted, unique lines in byte order, as comm expects.
sorted () { LC_ALL=C sort -u; }

# Lines of the first sorted list that are not in the second one.
minus () {  # list1 list2 (as files or process substitutions)
  LC_ALL=C comm -23 "$1" "$2"
}

require () {
  local cmd
  for cmd in "$@"; do
    command -v "$cmd" > /dev/null || die "$cmd is required"
  done
}

logged () {  # file|dir
  if [ -f "$LOG" ]; then
    sed -n "s|^$1 ||p" "$LOG" | sorted
  fi
}

check_prefix () {  # paths...
  local path
  for path in "$@"; do
    case $path in
      "$PREFIX"/*) ;;
      *) die "refusing to touch $path, which is outside $PREFIX" ;;
    esac
  done
}

remove_files () {  # files...
  [ $# -gt 0 ] || return 0
  check_prefix "$@"
  sudo rm -f -- "$@"
}

# Removes the given directories that are empty, deepest first.
prune_dirs () {  # dirs...
  local dir
  local -a dirs=()
  [ $# -gt 0 ] || return 0
  check_prefix "$@"
  mapfile -t dirs < <(lines "$@" | LC_ALL=C sort -r -u)
  for dir in "${dirs[@]}"; do
    if [ -d "$dir" ] && [ -z "$(find "$dir" -mindepth 1 -print -quit)" ]; then
      sudo rmdir -- "$dir"
    fi
  done
}

existing_dirs () {  # dirs...
  local dir
  for dir in "$@"; do
    if [ -d "$dir" ]; then
      echo "$dir"
    fi
  done
}

# Brings the icon, desktop and MIME caches in $PREFIX up to date. Meson's
# install runs utils/meson_post_install.py for the first two, but nothing
# updates $PREFIX/share/mime: Fedora's shared-mime-info only has a file
# trigger for /usr/share/mime. When no icons or MIME packages are left, the
# caches generated from them are removed instead.
update_caches () {
  local icons=$PREFIX/share/icons/hicolor
  local mime=$PREFIX/share/mime
  if [ -d "$icons" ]; then
    if [ -n "$(find "$icons" -type f -not -name icon-theme.cache -print -quit)" ]; then
      sudo gtk-update-icon-cache -qtf "$icons"
    else
      sudo rm -f -- "$icons/icon-theme.cache"
    fi
  fi
  if [ -d "$PREFIX/share/applications" ]; then
    sudo update-desktop-database -q "$PREFIX/share/applications"
  fi
  if [ -d "$mime" ]; then
    if [ -n "$(find "$mime/packages" -type f -print -quit 2> /dev/null)" ]; then
      sudo update-mime-database -n "$mime"
    else
      # Everything but packages/ is generated by update-mime-database.
      sudo find "$mime" -mindepth 1 -maxdepth 1 -not -name packages -exec rm -rf -- {} +
    fi
  fi
}

write_log () {  # comment files_list dirs_list (as files or process substitutions)
  mkdir -p "$STATE_DIR"
  {
    echo "# $1"
    sed 's|^|file |' "$2"
    sed 's|^|dir |' "$3"
  } > "$LOG.tmp"
  mv -- "$LOG.tmp" "$LOG"
}

uninstall () {
  local -a files=() dirs=()
  [ -f "$LOG" ] || die "nothing to uninstall: $LOG does not exist"
  mapfile -t files < <(logged file)
  mapfile -t dirs < <(logged dir)
  remove_files "${files[@]}"
  update_caches
  prune_dirs "${dirs[@]}"
  mapfile -t dirs < <(existing_dirs "${dirs[@]}")
  if [ ${#dirs[@]} -gt 0 ]; then
    echo "Kept these directories, which are not empty:" >&2
    printf '  %s\n' "${dirs[@]}" >&2
  fi
  rm -f -- "$LOG"
  rmdir --ignore-fail-on-non-empty -- "$STATE_DIR"
  echo "Removed Lutris from $PREFIX."
}

install () {
  local revision stage path
  local -a old_files=() old_dirs=() new_files=() new_dirs=() conflicts=() stale=() dirs=()
  [ "$EUID" -ne 0 ] || die "run this as your user; it uses sudo where needed"
  require git tar meson ninja msgfmt sudo gtk-update-icon-cache update-desktop-database update-mime-database
  if command -v rpm > /dev/null && rpm -q --quiet lutris; then
    die "Fedora's lutris package is installed; remove it first (sudo dnf remove lutris)"
  fi
  if [ -n "$(git -C "$REPO" status --porcelain --untracked-files=no)" ]; then
    die "$REPO has uncommitted changes; commit or stash them, only HEAD is installed"
  fi
  revision=$(git -C "$REPO" describe --tags --always HEAD)

  TMP=$(mktemp -d)
  trap 'rm -rf -- "$TMP"' EXIT
  mkdir "$TMP/src"
  git -C "$REPO" archive HEAD | tar -x -C "$TMP/src"
  meson setup "$TMP/build" "$TMP/src" --prefix="$PREFIX"
  meson compile -C "$TMP/build"

  # What the install will add: every file and symlink, and the directories
  # that do not exist yet.
  stage=$TMP/stage
  DESTDIR=$stage meson install -C "$TMP/build" --no-rebuild --quiet
  [ -d "$stage$PREFIX" ] || die "the staged install has nothing in $PREFIX"
  mapfile -t new_files < <(find "$stage$PREFIX" -not -type d | sed "s|^$stage||" | sorted)
  mapfile -t new_dirs < <(find "$stage$PREFIX" -mindepth 1 -type d | sed "s|^$stage||" | sorted)
  [ ${#new_files[@]} -gt 0 ] || die "the staged install has no files"
  mapfile -t old_files < <(logged file)
  mapfile -t old_dirs < <(logged dir)

  # Every file must either not exist yet or be one we installed before.
  mapfile -t conflicts < <(minus <(for path in "${new_files[@]}"; do
                                     if [ -e "$path" ] || [ -L "$path" ]; then echo "$path"; fi
                                   done) <(lines "${old_files[@]}"))
  if [ ${#conflicts[@]} -gt 0 ]; then
    printf '  %s\n' "${conflicts[@]}" >&2
    die "these files exist and were not installed by this script; remove them first"
  fi
  mapfile -t dirs < <(for path in "${new_dirs[@]}"; do
                        if [ ! -e "$path" ]; then echo "$path"; fi
                      done | cat - <(lines "${old_dirs[@]}") | sorted)

  # Record the old and new entries first, so that an interrupted install can
  # be repeated or uninstalled.
  write_log "Lutris $revision being installed by $REPO/arm64-16k/install.sh" \
            <(lines "${old_files[@]}" "${new_files[@]}" | sorted) <(lines "${dirs[@]}")
  echo "Installing Lutris $revision into $PREFIX (sudo)."
  sudo meson install -C "$TMP/build" --no-rebuild --quiet

  # Remove what the previous install had and this one no longer installs.
  mapfile -t stale < <(minus <(lines "${old_files[@]}") <(lines "${new_files[@]}"))
  remove_files "${stale[@]}"
  update_caches
  prune_dirs "${dirs[@]}"
  mapfile -t dirs < <(existing_dirs "${dirs[@]}")

  write_log "Lutris $revision installed by $REPO/arm64-16k/install.sh" \
            <(lines "${new_files[@]}") <(lines "${dirs[@]}")
  echo "Installed Lutris $revision as $PREFIX/bin/lutris."
}

case ${1:-} in
  "") install ;;
  --uninstall) uninstall ;;
  *) die "unknown option '$1'" ;;
esac
